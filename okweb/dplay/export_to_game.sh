#!/usr/bin/env bash
# Copy our browser DirectPlay into a game's tree as a versioned third-party library:
#   okweb/dplay/export_to_game.sh <game dir>     (the game's checkout)
# -> <game dir>/third_party/classic-netplay/
#      src/      dplayx (Wine-derived, ours), winweb, the okweb provider, the flat C API
#      include/  okweb_dplay.h (what the game includes) + DirectPlay/Windows headers for src/
#      web/      okweb.js + okweb-sp.js (the page side; or load them from oldkid.net/aoe2net/sdk/v1/)
#      CMakeLists.txt, VERSION, LICENSE (LGPL 2.1), README.md
# The copy is replaced as a whole each time: change things here, never in the game's copy.
set -e
cd "$(dirname "$0")"
GAME=${1:?game directory}
DST="$GAME/third_party/classic-netplay"
W=../../winedplay
[ -d "$GAME" ] || { echo "no such directory: $GAME"; exit 1; }
rm -rf "$DST"
mkdir -p "$DST/src/dplayx" "$DST/include/win32" "$DST/include/dplay/wine" "$DST/web"
for f in $W/port/dlls/dplayx/*.c $W/port/dlls/dplayx/*.h; do
    case $(basename "$f") in builtin.c) continue ;; esac   # (the Windows drop-in's UI)
    cp "$f" "$DST/src/dplayx/"
done
cp $W/shim/winedbg_shim.c winweb.c okweb_sp.c okweb_password.c guids.c okweb_flat.c "$DST/src/"
cp win32/*.h "$DST/include/win32/"
cp $W/port/include/dplay.h $W/port/include/dplobby.h "$DST/include/dplay/"
cp $W/port/include/wine/*.h "$DST/include/dplay/wine/"
cp include/okweb_dplay.h "$DST/include/"
cp ../sdk/v1/okweb.js ../sdk/v1/okweb-sp.js "$DST/web/"
cp legal/LGPL-2.1.txt "$DST/LICENSE"
REV=$(git -C .. rev-parse --short HEAD 2>/dev/null || echo unknown)
DIRTY=$(git -C .. status --porcelain -- . ../sdk ../../winedplay/port ../../winedplay/shim 2>/dev/null | head -1)
printf 'classic-netplay okweb-dplay %s\nfrom %s%s, %s\n' "1.0.0" "$REV" "${DIRTY:+ + local changes}" "$(date +%Y-%m-%d)" > "$DST/VERSION"

cat > "$DST/CMakeLists.txt" <<'EOF'
# classic-netplay: our DirectPlay (Wine-derived) for the browser, as a static library.
# Generated by okweb/dplay/export_to_game.sh - edit the source tree, not this copy.
file(GLOB CLASSIC_NETPLAY_SRC ${CMAKE_CURRENT_LIST_DIR}/src/dplayx/*.c ${CMAKE_CURRENT_LIST_DIR}/src/*.c)
add_library(classic_netplay STATIC ${CLASSIC_NETPLAY_SRC})
target_include_directories(classic_netplay PRIVATE
    ${CMAKE_CURRENT_LIST_DIR}/include/win32 ${CMAKE_CURRENT_LIST_DIR}/include/dplay
    ${CMAKE_CURRENT_LIST_DIR}/src/dplayx ${CMAKE_CURRENT_LIST_DIR}/src ${CMAKE_CURRENT_LIST_DIR}/include)
target_include_directories(classic_netplay INTERFACE ${CMAKE_CURRENT_LIST_DIR}/include)
# -fshort-wchar: DirectPlay's WCHAR is 16-bit (as on Windows); -fno-builtin: keep the optimizer from
# turning its 16-bit string loops into the C library's 32-bit wcslen
target_compile_options(classic_netplay PRIVATE -fshort-wchar -fno-builtin -w)
target_compile_definitions(classic_netplay PRIVATE __WINESRC__ OKWEB_DPLAY WINE_NOWINSOCK)
# the game links with -sASYNCIFY: DirectPlay waits for replies while a player joins
EOF

cat > "$DST/README.md" <<'EOF'
# classic-netplay (okweb-dplay)

Our DirectPlay for the browser: Wine's DirectPlay, conformance-tested against Windows, compiled to
WebAssembly, with "Oldkid.net Online Play" as the connection (browser to browser over WebRTC,
games found through an okplay.php room server). A versioned copy - see VERSION; it is replaced as a
whole by `okweb/dplay/export_to_game.sh` in the Classic Netplay tree. Licence: LGPL 2.1 (LICENSE).

- Game code includes `include/okweb_dplay.h` (plain C, no Windows types) and links `classic_netplay`
  (CMakeLists.txt here) with `-sASYNCIFY`.
- The page installs the provider before the game starts multiplayer:
  `import { installOkwebProvider } from './okweb-sp.js'; installOkwebProvider(Module, { server, playerName });`
  (`web/` holds okweb.js and okweb-sp.js; or load them from https://oldkid.net/aoe2net/sdk/v1/).
EOF
echo "exported to $DST ($(find "$DST" -type f | wc -l) files, $(cat "$DST/VERSION" | head -2 | tr '\n' ' '))"
